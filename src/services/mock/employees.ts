// Mock EmployeeAdminApi backed by the in-browser mock backend. Enforces the same permission
// checks and business rules a real backend must apply.
import {
  CreateEmployeeInput,
  RoleInput,
  UpdateEmployeeInput,
  UpdateRoleInput,
  type EmployeeAdminApi,
  type EmployeeRow,
  type JsonValue,
  type RoleRecord,
} from "../contracts/employees";
import { ALL_PERMISSIONS } from "../permissions";
import {
  assertKeepsAdministrator,
  generateTemporaryPassword,
  resolveStatusChange,
  roleDeletionBlocker,
} from "../employee-rules";
import {
  ADMIN_ROLE,
  activeCaller,
  audit,
  findEmployee,
  fullName,
  hashPassword,
  newId,
  nowIso,
  otherActiveAdmins,
  readTables,
  requirePermission,
  roleOf,
  writeTables,
  type MockTables,
} from "./backend";

function assertUniqueRoleName(t: MockTables, name: string, excludeId?: string) {
  if (t.roles.some((r) => r.id !== excludeId && r.name.toLowerCase() === name.toLowerCase()))
    throw new Error("A role with this name already exists.");
}

export const mockEmployeeAdminApi: EmployeeAdminApi = {
  async getDirectory() {
    const t = readTables();
    if (!activeCaller(t)) throw new Error("The employee directory couldn't be loaded.");
    return structuredClone({ employees: t.employees, roles: t.roles, assignments: t.assignments });
  },

  async listAuditEvents() {
    const t = readTables();
    requirePermission(t, "audit.view");
    return structuredClone(t.audit);
  },

  async createEmployee(raw) {
    const data = CreateEmployeeInput.parse(raw);
    const t = readTables();
    const actor = requirePermission(t, "employees.manage");
    const role = t.roles.find((r) => r.id === data.roleId);
    if (!role) throw new Error("Choose a valid role.");
    if (t.employees.some((e) => e.email === data.email))
      throw new Error("An employee with this work email already exists.");

    const id = newId();
    const temporaryPassword = generateTemporaryPassword();
    const hash = await hashPassword(id, temporaryPassword);
    const employeeCode = writeTables((x) => {
      const at = nowIso();
      const code = `EMP-${x.nextEmployeeNumber++}`;
      x.employees.push({
        id,
        employee_code: code,
        first_name: data.firstName,
        last_name: data.lastName,
        email: data.email,
        department: data.department,
        job_title: data.jobTitle,
        phone: data.phone,
        status: "Invitation Pending",
        must_change_password: true,
        last_login_at: null,
        created_by: actor.id,
        created_at: at,
        updated_at: at,
      });
      x.credentials[id] = hash;
      x.assignments.push({ user_id: id, role_id: role.id, assigned_at: at });
      audit(x, actor.id, {
        action: "Employee account created",
        entityType: "Employee",
        entityId: id,
        entityLabel: `${data.firstName} ${data.lastName}`,
        details: `${code} · ${role.name} · ${data.department}. Temporary password generated by the system.`,
        after: { role: role.name, department: data.department, status: "Invitation Pending" },
      });
      return code;
    });
    return { id, employeeCode, temporaryPassword };
  },

  async updateEmployee(raw) {
    const data = UpdateEmployeeInput.parse(raw);
    return writeTables((t) => {
      const actor = requirePermission(t, "employees.manage");
      const target = findEmployee(t, data.id);
      if (!target) throw new Error("Employee not found.");
      const self = data.id === actor.id;
      const currentRole = roleOf(t, data.id);

      let nextRole = currentRole;
      if (data.roleId && data.roleId !== currentRole?.id) {
        if (self) throw new Error("You can't change your own role.");
        nextRole = t.roles.find((r) => r.id === data.roleId) ?? null;
        if (!nextRole) throw new Error("Choose a valid role.");
      }
      let nextStatus = target.status;
      if (data.status && data.status !== target.status) {
        if (self) throw new Error("You can't change your own account status.");
        nextStatus = resolveStatusChange(data.status, target.must_change_password);
      }
      const wasActiveAdmin = target.status === "Active" && currentRole?.name === ADMIN_ROLE;
      const remains = nextStatus === "Active" && nextRole?.name === ADMIN_ROLE;
      if (wasActiveAdmin && !remains)
        assertKeepsAdministrator({
          targetIsActiveAdmin: true,
          remainsActiveAdmin: false,
          otherActiveAdmins: otherActiveAdmins(t, data.id),
        });

      const patch: Partial<EmployeeRow> = {};
      if (data.firstName !== undefined) patch.first_name = data.firstName;
      if (data.lastName !== undefined) patch.last_name = data.lastName;
      if (data.department !== undefined) patch.department = data.department;
      if (data.jobTitle !== undefined) patch.job_title = data.jobTitle || null;
      if (data.phone !== undefined) patch.phone = data.phone || null;
      if (nextStatus !== target.status) patch.status = nextStatus;

      const before: Record<string, JsonValue> = {};
      const after: Record<string, JsonValue> = {};
      for (const [k, v] of Object.entries(patch)) {
        const prev = target[k as keyof EmployeeRow];
        if (prev === v) continue;
        before[k] = prev ?? null;
        after[k] = v ?? null;
      }
      Object.assign(target, patch, Object.keys(patch).length ? { updated_at: nowIso() } : {});
      if (nextRole && nextRole.id !== currentRole?.id) {
        t.assignments = [
          ...t.assignments.filter((a) => a.user_id !== data.id),
          { user_id: data.id, role_id: nextRole.id, assigned_at: nowIso() },
        ];
        before.role = currentRole?.name ?? null;
        after.role = nextRole.name;
      }
      const action =
        "status" in after
          ? "Employee status changed"
          : "role" in after
            ? "Employee role changed"
            : "Employee details updated";
      if (Object.keys(after).length)
        audit(t, actor.id, {
          action,
          entityType: "Employee",
          entityId: data.id,
          entityLabel: fullName(target),
          details: data.reason ?? "",
          before,
          after,
        });
      return { status: nextStatus };
    });
  },

  async resetPassword(employeeId) {
    const t = readTables();
    const actor = requirePermission(t, "employees.manage");
    if (employeeId === actor.id) throw new Error("You can't reset your own password here.");
    const target = findEmployee(t, employeeId);
    if (!target) throw new Error("Employee not found.");
    const temporaryPassword = generateTemporaryPassword();
    const hash = await hashPassword(target.id, temporaryPassword);
    writeTables((x) => {
      const emp = findEmployee(x, employeeId)!;
      x.credentials[emp.id] = hash;
      emp.must_change_password = true;
      emp.updated_at = nowIso();
      audit(x, actor.id, {
        action: "Password reset by administrator",
        entityType: "Employee",
        entityId: emp.id,
        entityLabel: fullName(emp),
        details: "New temporary password generated by the system.",
      });
    });
    return { temporaryPassword };
  },

  async createRole(raw) {
    const data = RoleInput.parse(raw);
    return writeTables((t) => {
      const actor = requirePermission(t, "roles.manage");
      if (!data.permissions.length) throw new Error("Choose at least one permission.");
      assertUniqueRoleName(t, data.name);
      const at = nowIso();
      const role: RoleRecord = {
        id: newId(),
        name: data.name,
        description: data.description,
        department: data.department,
        landing_page: data.landingPage,
        permissions: data.permissions,
        is_system: false,
        created_at: at,
        updated_at: at,
      };
      t.roles.push(role);
      audit(t, actor.id, {
        action: "Role created",
        entityType: "Role",
        entityId: role.id,
        entityLabel: role.name,
        details: `${role.permissions.length} permissions`,
        after: { permissions: role.permissions.join(", ") },
      });
      return structuredClone(role);
    });
  },

  async updateRole(raw) {
    const data = UpdateRoleInput.parse(raw);
    return writeTables((t) => {
      const actor = requirePermission(t, "roles.manage");
      const role = t.roles.find((r) => r.id === data.id);
      if (!role) throw new Error("Role not found.");
      if (role.is_system && data.name !== role.name)
        throw new Error("System roles can't be renamed.");
      const permissions: string[] =
        role.is_system && role.name === ADMIN_ROLE ? [...ALL_PERMISSIONS] : data.permissions;
      if (!permissions.length) throw new Error("Choose at least one permission.");
      assertUniqueRoleName(t, data.name, role.id);
      const prev = structuredClone(role);
      Object.assign(role, {
        name: data.name,
        description: data.description,
        department: data.department,
        landing_page: data.landingPage,
        permissions,
        updated_at: nowIso(),
      });
      const added = permissions.filter((p) => !prev.permissions.includes(p));
      const removed = prev.permissions.filter((p) => !permissions.includes(p));
      audit(t, actor.id, {
        action: "Role updated",
        entityType: "Role",
        entityId: role.id,
        entityLabel: role.name,
        details: [
          added.length && `Added: ${added.join(", ")}`,
          removed.length && `Removed: ${removed.join(", ")}`,
        ]
          .filter(Boolean)
          .join(" · "),
        before: {
          name: prev.name,
          landing_page: prev.landing_page,
          permissions: prev.permissions.length,
        },
        after: {
          name: role.name,
          landing_page: role.landing_page,
          permissions: role.permissions.length,
        },
      });
      return structuredClone(role);
    });
  },

  async deleteRole(roleId) {
    writeTables((t) => {
      const actor = requirePermission(t, "roles.manage");
      const role = t.roles.find((r) => r.id === roleId);
      if (!role) throw new Error("Role not found.");
      const blocker = roleDeletionBlocker(
        role,
        t.assignments.filter((a) => a.role_id === role.id).length,
      );
      if (blocker) throw new Error(blocker);
      t.roles = t.roles.filter((r) => r.id !== role.id);
      audit(t, actor.id, {
        action: "Role deleted",
        entityType: "Role",
        entityId: role.id,
        entityLabel: role.name,
      });
    });
  },
};
